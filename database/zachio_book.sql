DROP DATABASE IF EXISTS zachio_book;
CREATE DATABASE zachio_book CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE zachio_book;

-- ===== Пользователи и вход =====

-- учетные записи (и студенты, и преподаватели)
CREATE TABLE users (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('student', 'teacher') NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  patronymic VARCHAR(100) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- сессии входа: каждому выданному токену соответствует запись, при выходе она отзывается
CREATE TABLE user_session (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  token_id VARCHAR(64) NOT NULL UNIQUE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NOT NULL,
  revoked_at DATETIME NULL,
  CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE student_group (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE student (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL UNIQUE,
  group_id INT NOT NULL,
  CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_student_group FOREIGN KEY (group_id) REFERENCES student_group(id)
);

CREATE TABLE teacher (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL UNIQUE,
  CONSTRAINT fk_teacher_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ===== Дисциплины и курсы =====

-- общий справочник дисциплин (преподаватель может добавить свою)
CREATE TABLE discipline (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  created_by_teacher_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_discipline_teacher FOREIGN KEY (created_by_teacher_id) REFERENCES teacher(id) ON DELETE SET NULL
);

-- курс = дисциплина, выбранная преподавателем
CREATE TABLE course (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  teacher_id INT NOT NULL,
  discipline_id INT NOT NULL,
  description TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_course UNIQUE (teacher_id, discipline_id),
  CONSTRAINT fk_course_teacher FOREIGN KEY (teacher_id) REFERENCES teacher(id) ON DELETE CASCADE,
  CONSTRAINT fk_course_discipline FOREIGN KEY (discipline_id) REFERENCES discipline(id) ON DELETE CASCADE
);

-- группы, которые преподаватель записал на свой курс
CREATE TABLE course_group (
  course_id INT NOT NULL,
  group_id INT NOT NULL,
  PRIMARY KEY (course_id, group_id),
  CONSTRAINT fk_cg_course FOREIGN KEY (course_id) REFERENCES course(id) ON DELETE CASCADE,
  CONSTRAINT fk_cg_group FOREIGN KEY (group_id) REFERENCES student_group(id) ON DELETE CASCADE
);

-- ===== Файлы =====

-- загруженные файлы (материалы занятий, файлы заданий, сданные работы, вложения сообщений)
CREATE TABLE attachment (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes INT NOT NULL,
  uploaded_by INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_attachment_user FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ===== Модули и занятия =====

CREATE TABLE module (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  course_id INT NOT NULL,
  name VARCHAR(255) NOT NULL,
  CONSTRAINT fk_module_course FOREIGN KEY (course_id) REFERENCES course(id) ON DELETE CASCADE
);

-- занятие: дата, время (номер пары 1-6), кабинет - отображается в расписании
-- status: pending - закрыто, open - открыто, completed - завершено
CREATE TABLE lesson (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  module_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  lesson_type ENUM('lecture', 'practice', 'lab', 'consultation', 'seminar') NOT NULL,
  lesson_date DATE NOT NULL,
  time_slot TINYINT NOT NULL,
  room VARCHAR(50) NOT NULL,
  topics TEXT NULL,
  duration VARCHAR(50) NULL,
  status ENUM('pending', 'open', 'completed') NOT NULL DEFAULT 'pending',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_lesson_slot CHECK (time_slot BETWEEN 1 AND 6),
  CONSTRAINT fk_lesson_module FOREIGN KEY (module_id) REFERENCES module(id) ON DELETE CASCADE
);

-- группы, которым открыт доступ к занятию
CREATE TABLE lesson_group (
  lesson_id INT NOT NULL,
  group_id INT NOT NULL,
  PRIMARY KEY (lesson_id, group_id),
  CONSTRAINT fk_lg_lesson FOREIGN KEY (lesson_id) REFERENCES lesson(id) ON DELETE CASCADE,
  CONSTRAINT fk_lg_group FOREIGN KEY (group_id) REFERENCES student_group(id) ON DELETE CASCADE
);

-- материалы занятия
CREATE TABLE lesson_file (
  lesson_id INT NOT NULL,
  attachment_id INT NOT NULL,
  PRIMARY KEY (lesson_id, attachment_id),
  CONSTRAINT fk_lf_lesson FOREIGN KEY (lesson_id) REFERENCES lesson(id) ON DELETE CASCADE,
  CONSTRAINT fk_lf_attachment FOREIGN KEY (attachment_id) REFERENCES attachment(id) ON DELETE CASCADE
);

-- просмотренные студентом занятия ("прочитал лекцию")
CREATE TABLE lesson_view (
  student_id INT NOT NULL,
  lesson_id INT NOT NULL,
  viewed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (student_id, lesson_id),
  CONSTRAINT fk_lv_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE,
  CONSTRAINT fk_lv_lesson FOREIGN KEY (lesson_id) REFERENCES lesson(id) ON DELETE CASCADE
);

-- ===== Задания =====

CREATE TABLE assignment (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  course_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  start_date DATE NOT NULL,
  due_date DATE NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_assignment_dates CHECK (due_date >= start_date),
  CONSTRAINT fk_assignment_course FOREIGN KEY (course_id) REFERENCES course(id) ON DELETE CASCADE
);

CREATE TABLE assignment_group (
  assignment_id INT NOT NULL,
  group_id INT NOT NULL,
  PRIMARY KEY (assignment_id, group_id),
  CONSTRAINT fk_ag_assignment FOREIGN KEY (assignment_id) REFERENCES assignment(id) ON DELETE CASCADE,
  CONSTRAINT fk_ag_group FOREIGN KEY (group_id) REFERENCES student_group(id) ON DELETE CASCADE
);

CREATE TABLE assignment_file (
  assignment_id INT NOT NULL,
  attachment_id INT NOT NULL,
  PRIMARY KEY (assignment_id, attachment_id),
  CONSTRAINT fk_af_assignment FOREIGN KEY (assignment_id) REFERENCES assignment(id) ON DELETE CASCADE,
  CONSTRAINT fk_af_attachment FOREIGN KEY (attachment_id) REFERENCES attachment(id) ON DELETE CASCADE
);

-- сданная студентом работа (повторная отправка заменяет предыдущую)
CREATE TABLE submission (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  assignment_id INT NOT NULL,
  student_id INT NOT NULL,
  comment TEXT NULL,
  attachment_id INT NULL,
  submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_submission UNIQUE (assignment_id, student_id),
  CONSTRAINT fk_submission_assignment FOREIGN KEY (assignment_id) REFERENCES assignment(id) ON DELETE CASCADE,
  CONSTRAINT fk_submission_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE,
  CONSTRAINT fk_submission_attachment FOREIGN KEY (attachment_id) REFERENCES attachment(id) ON DELETE SET NULL
);

-- ===== Оценки и посещаемость =====

-- grade_type: control - контрольная, independent - самостоятельная, laboratory - лабораторная,
--             board - выход к доске, final - финальная оценка (одна на курс)
CREATE TABLE grade (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  course_id INT NOT NULL,
  grade_type ENUM('control', 'independent', 'laboratory', 'board', 'final') NOT NULL,
  grade_value TINYINT NOT NULL,
  grade_date DATE NOT NULL,
  comment VARCHAR(255) NULL,
  CONSTRAINT chk_grade_value CHECK (grade_value BETWEEN 1 AND 5),
  CONSTRAINT fk_grade_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE,
  CONSTRAINT fk_grade_course FOREIGN KEY (course_id) REFERENCES course(id) ON DELETE CASCADE
);

CREATE TABLE attendance (
  lesson_id INT NOT NULL,
  student_id INT NOT NULL,
  is_present TINYINT NOT NULL,
  marked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (lesson_id, student_id),
  CONSTRAINT fk_attendance_lesson FOREIGN KEY (lesson_id) REFERENCES lesson(id) ON DELETE CASCADE,
  CONSTRAINT fk_attendance_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE
);

-- ===== Сообщения =====

-- диалог студента с преподавателем по дисциплине (подряд идущие письма образуют чат)
CREATE TABLE conversation (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  teacher_id INT NOT NULL,
  course_id INT NULL,
  subject VARCHAR(255) NOT NULL,
  updated_at DATETIME NOT NULL,
  CONSTRAINT fk_conversation_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE,
  CONSTRAINT fk_conversation_teacher FOREIGN KEY (teacher_id) REFERENCES teacher(id) ON DELETE CASCADE,
  CONSTRAINT fk_conversation_course FOREIGN KEY (course_id) REFERENCES course(id) ON DELETE SET NULL
);

CREATE TABLE message (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  conversation_id INT NOT NULL,
  sender_role ENUM('student', 'teacher') NOT NULL,
  subject VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  attachment_id INT NULL,
  created_at DATETIME NOT NULL,
  is_read TINYINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation(id) ON DELETE CASCADE,
  CONSTRAINT fk_message_attachment FOREIGN KEY (attachment_id) REFERENCES attachment(id) ON DELETE SET NULL
);

-- ===== Последние действия студента =====

CREATE TABLE activity (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  activity_type VARCHAR(30) NOT NULL,
  description VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_activity_student FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE CASCADE
);

